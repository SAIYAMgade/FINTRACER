from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import PlainTextResponse
from sqlalchemy.orm import Session
from app.db.session import get_db
from app.models.entities import InvestigationReport

router = APIRouter(prefix="/reports", tags=["Reports"])

@router.get("")
def list_reports(db: Session = Depends(get_db)):
    reports = db.query(InvestigationReport).order_by(InvestigationReport.created_at.desc()).all()
    return [
        {
            "id": r.id,
            "title": r.title,
            "status": r.status,
            "data_as_of": r.data_as_of.isoformat() if r.data_as_of else None,
            "version": r.report_version,
            "created_at": r.created_at.isoformat() if r.created_at else None,
        }
        for r in reports
    ]

@router.get("/{report_id}")
def get_report(report_id: int, db: Session = Depends(get_db)):
    r = db.query(InvestigationReport).filter(InvestigationReport.id == report_id).first()
    if not r:
        raise HTTPException(status_code=404, detail="Report not found")
    
    return {
        "id": r.id,
        "investigation_id": r.investigation_id,
        "title": r.title,
        "status": r.status,
        "data_as_of": r.data_as_of.isoformat() if r.data_as_of else None,
        "version": r.report_version,
        "executive_summary": r.executive_summary,
        "snapshot": r.result_snapshot_json,
        "recommendations": r.recommendations_json or [],
        "methodology": r.methodology_notes,
        "limitations": r.limitations_notes,
        "created_at": r.created_at.isoformat() if r.created_at else None,
    }

@router.get("/{report_id}/export")
def export_report_markdown(report_id: int, format: str = Query("md"), db: Session = Depends(get_db)):
    r = db.query(InvestigationReport).filter(InvestigationReport.id == report_id).first()
    if not r:
        raise HTTPException(status_code=404, detail="Report not found")

    snapshot = r.result_snapshot_json or {}
    evidence = snapshot.get("evidence_panel", {})

    md_lines = [
        f"# {r.title}",
        f"**Report Version:** {r.report_version} | **Status:** {r.status} | **Data As Of:** {r.data_as_of}",
        "",
        "## 1. Executive Summary",
        r.executive_summary or "No executive summary provided.",
        "",
        "## 2. Core Finding & Evidence",
        f"**Finding:** {evidence.get('finding_title', 'N/A')}",
        f"**Business Question:** {evidence.get('business_question', 'N/A')}",
        f"**Sample Size:** {evidence.get('sample_size', 'N/A')}",
        f"**Metric Definitions:** {evidence.get('metric_definitions', 'N/A')}",
        "",
        "## 3. Analytical Methodology & Reproducibility",
        f"{r.methodology_notes or 'PostgreSQL relational query aggregation.'}",
        "",
        "```sql",
        f"{evidence.get('sql_reference', '-- No SQL captured')}",
        "```",
        "",
        "## 4. Recommendations & Follow-Up Actions",
    ]

    for rec in (r.recommendations_json or []):
        md_lines.append(f"- {rec}")

    md_lines.extend([
        "",
        "## 5. Limitations & Caveats",
        f"{r.limitations_notes or 'Observational data caveats apply.'}",
        f"- {evidence.get('caveats', '')}",
        "",
        "---",
        "*Generated by FINTRACER Financial Analytics & Investigation Platform*"
    ])

    return PlainTextResponse("\n".join(md_lines), media_type="text/markdown")
